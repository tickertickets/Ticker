-- Ticker music layer. Additive only: existing movie tables and data are untouched.
-- Safe to paste into Supabase SQL Editor after taking a database backup.

CREATE TABLE IF NOT EXISTS public.music_items (
  provider_id text NOT NULL,
  entity text NOT NULL CHECK (entity IN ('song', 'album', 'artist')),
  name text NOT NULL,
  artist_name text,
  collection_name text,
  artwork_url text,
  preview_url text,
  item_url text,
  genre text,
  release_date text,
  duration_ms integer,
  track_count integer,
  raw jsonb NOT NULL DEFAULT '{}'::jsonb,
  fetched_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (provider_id, entity)
);

CREATE INDEX IF NOT EXISTS music_items_entity_fetched_idx
  ON public.music_items (entity, fetched_at DESC);

CREATE TABLE IF NOT EXISTS public.music_vinyls (
  id text PRIMARY KEY,
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  track_id text NOT NULL,
  item_snapshot jsonb NOT NULL,
  rating numeric(2,1) CHECK (rating IS NULL OR (rating >= 0 AND rating <= 5)),
  rating_type text NOT NULL DEFAULT 'star',
  hide_rating boolean NOT NULL DEFAULT false,
  caption text NOT NULL DEFAULT '',
  shape text NOT NULL DEFAULT 'vinyl' CHECK (shape IN ('vinyl', 'square')),
  is_private boolean NOT NULL DEFAULT false,
  deleted_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  edited_at timestamptz
);

ALTER TABLE public.music_vinyls
  ADD COLUMN IF NOT EXISTS rating_type text NOT NULL DEFAULT 'star';
ALTER TABLE public.music_vinyls
  ADD COLUMN IF NOT EXISTS hide_rating boolean NOT NULL DEFAULT false;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'music_vinyls_rating_type_valid_check'
      AND conrelid = 'public.music_vinyls'::regclass
  ) THEN
    ALTER TABLE public.music_vinyls
      ADD CONSTRAINT music_vinyls_rating_type_valid_check
      CHECK (rating_type IN ('star', 'blackhole'));
  END IF;
END
$$;

CREATE INDEX IF NOT EXISTS music_vinyls_user_created_idx
  ON public.music_vinyls (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS music_vinyls_created_idx
  ON public.music_vinyls (created_at DESC);
CREATE INDEX IF NOT EXISTS music_vinyls_public_track_ratings_idx
  ON public.music_vinyls (track_id, created_at DESC)
  WHERE deleted_at IS NULL AND is_private = false AND hide_rating = false AND rating IS NOT NULL;
CREATE INDEX IF NOT EXISTS music_vinyls_public_feed_idx
  ON public.music_vinyls (created_at DESC, user_id)
  WHERE deleted_at IS NULL AND is_private = false;

-- Apple documents an approximate limit of 20 Search API calls per minute.
-- This shared database-backed guard applies across all API server replicas.
CREATE TABLE IF NOT EXISTS public.music_provider_rate_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requested_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS music_provider_rate_events_requested_at_idx
  ON public.music_provider_rate_events (requested_at DESC);

CREATE OR REPLACE FUNCTION public.try_acquire_music_provider_slot()
RETURNS boolean
LANGUAGE plpgsql
AS $$
DECLARE
  current_time timestamptz := clock_timestamp();
  recent_count integer;
BEGIN
  PERFORM pg_advisory_xact_lock(781520246);
  DELETE FROM public.music_provider_rate_events
    WHERE requested_at < current_time - INTERVAL '60 seconds';
  SELECT count(*) INTO recent_count
    FROM public.music_provider_rate_events
    WHERE requested_at >= current_time - INTERVAL '60 seconds';
  IF recent_count >= 20 THEN
    RETURN false;
  END IF;
  INSERT INTO public.music_provider_rate_events (requested_at) VALUES (current_time);
  RETURN true;
END
$$;

CREATE TABLE IF NOT EXISTS public.music_playlists (
  id text PRIMARY KEY,
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  title text NOT NULL CHECK (length(title) BETWEEN 1 AND 100),
  description text NOT NULL DEFAULT '',
  cover_url text,
  is_private boolean NOT NULL DEFAULT false,
  deleted_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS music_playlists_user_created_idx
  ON public.music_playlists (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS music_playlists_created_idx
  ON public.music_playlists (created_at DESC);
CREATE INDEX IF NOT EXISTS music_playlists_public_feed_idx
  ON public.music_playlists (created_at DESC, user_id)
  WHERE deleted_at IS NULL AND is_private = false;

CREATE TABLE IF NOT EXISTS public.music_playlist_saves (
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  playlist_id text NOT NULL REFERENCES public.music_playlists(id) ON DELETE CASCADE,
  status text NOT NULL CHECK (status = 'listened'),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, playlist_id)
);

CREATE INDEX IF NOT EXISTS music_playlist_saves_user_status_idx
  ON public.music_playlist_saves (user_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.music_playlist_items (
  playlist_id text NOT NULL REFERENCES public.music_playlists(id) ON DELETE CASCADE,
  track_id text NOT NULL,
  item_snapshot jsonb NOT NULL,
  position integer NOT NULL CHECK (position >= 0),
  added_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (playlist_id, track_id)
);

CREATE INDEX IF NOT EXISTS music_playlist_items_order_idx
  ON public.music_playlist_items (playlist_id, position);

CREATE TABLE IF NOT EXISTS public.music_saves (
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  provider_id text NOT NULL,
  entity text NOT NULL CHECK (entity IN ('song', 'album', 'artist')),
  item_snapshot jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, provider_id, entity)
);

CREATE INDEX IF NOT EXISTS music_saves_item_idx
  ON public.music_saves (entity, provider_id);
